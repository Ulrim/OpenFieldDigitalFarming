function plainAction(a) {
  const text = `${a.device} ${a.command}`;
  for (const [re, [what, why]] of PLAIN_ACTION) if (re.test(text)) return { what, why };
  /* 짝이 없는 '알림'은 할 일이 아니다. 이 화면 자체가 그 알림이라서,
     목록에 올리면 '알림 고온·건조 주의 알림' 같은 줄이 생긴다. 위에
     이미 큰 글씨로 적혀 있는 것을 번호까지 붙여 되풀이하는 셈이다.
     뜻이 있는 알림(서리 경보 → 내일 아침 잎 끝 살펴보기)은 PLAIN_ACTION
     에 짝이 있으므로 여기까지 내려오지 않는다. */
  if (a.device === "알림") return null;
  return { what: `${a.device} ${a.command}`, why: a.reason };
}

/* 왜 그런지를 한 문장으로. 숫자는 그대로 쓰되 말은 쉽게. */
function plainWhy(risk, env, judgement) {
  const get = (k) => (env.find((e) => e.key === k) || {}).value;
  const t = get("t_air"), c = get("canopy_temp"), w = get("wind_speed"),
        h = get("rh"), wet = get("leaf_wetness");
  // 판단근거 문장도 실측을 먼저 쓴다
  const s = get("soil_moisture") ?? get("soil_index");
  if (risk === "frost")
    return `잎 높이 온도가 <b>${c}℃</b>까지 내려갔습니다. 바람이 <b>${w}m/s</b>로 거의 없어 새벽에 더 떨어집니다.`;
  if (risk === "heat_dry")
    return `기온 <b>${t}℃</b>에 흙 수분이 <b>${s}</b>까지 떨어졌습니다.`;
  if (risk === "rain_wet")
    return `흙 수분이 <b>${s}</b>이고 비가 이어집니다. 물이 빠질 자리가 필요합니다.`;
  if (risk === "disease")
    return `습도 <b>${h}%</b>에 잎이 ${wet >= 0.5 ? "젖어 있습니다" : "젖기 시작합니다"}. 이 상태가 길어지면 병이 번집니다.`;
  if (judgement && judgement.evidence.length)
    return judgement.evidence.map((e) => `${e.label} ${e.value}`).join(", ");
  return "";
}
